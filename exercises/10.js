console.log("--- Простые числа из интервала от 2 до 10 ---");

// Перебор чисел в заданном интервале от 2 до 10
for (let i = 2; i <= 10; i++) {
  let isPrime = true;

  // Проверка, делится ли число i на какое-либо другое число, кроме 1 и себя
  for (let j = 2; j < i; j++) {
    if (i % j === 0) {
      isPrime = false; // Нашелся делитель, число не простое
      break;
    }
  }

  // Если делителей не нашлось, вывод простого числа в консоль
  if (isPrime) {
    console.log(`Число ${i} — простое`);
  }
}
